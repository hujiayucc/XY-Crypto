import java.nio.*;
import java.nio.charset.*;
import java.nio.file.*;
import java.util.*;

/** Generate mapping data from Java's GBK charset without copying codec source. */
public class GenerateGbk {
  public static void main(String[] args) throws Exception {
    Charset cs = Charset.forName("GBK");
    CharsetEncoder enc = cs.newEncoder().onUnmappableCharacter(CodingErrorAction.REPORT).onMalformedInput(CodingErrorAction.REPORT);
    CharsetDecoder dec = cs.newDecoder().onUnmappableCharacter(CodingErrorAction.REPORT).onMalformedInput(CodingErrorAction.REPORT);
    StringBuilder out = new StringBuilder("// Generated by tool/GenerateGbk.java using OpenJDK GBK.\n// Mapping data only; regenerate with the documented JDK when updating.\nconst gbkEncodeMap = <int, int>{\n");
    int count = 0;
    for (int c = 128; c <= 65535; c++) {
      try {
        ByteBuffer b = enc.encode(CharBuffer.wrap(new char[]{(char)c}));
        int code = 0;
        while(b.hasRemaining()) code = (code << 8) | (b.get() & 255);
        out.append(c).append(':').append(code).append(',');
        if (++count % 8 == 0) out.append('\n');
      } catch (CharacterCodingException ignored) { }
    }
    out.append("\n};\nconst gbkDecodeMap = <int, int>{\n");
    for (int n = 128; n <= 65535; n++) {
      if (n > 255 && ((n >> 8) < 0x81 || (n >> 8) > 0xfe)) continue;
      byte[] bytes = n <= 255 ? new byte[]{(byte)n} : new byte[]{(byte)(n>>8),(byte)n};
      try {
        CharBuffer chars = dec.decode(ByteBuffer.wrap(bytes));
        if (chars.remaining() != 1) continue;
        out.append(n).append(':').append((int)chars.get()).append(',');
        if (++count % 8 == 0) out.append('\n');
      } catch (CharacterCodingException ignored) { }
    }
    out.append("\n};\n");
    Files.writeString(Path.of(args[0]), out.toString());
    System.out.println("GBK mappings generated: " + count);
  }
}